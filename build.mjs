#!/usr/bin/env node
/* build.mjs — assembles src/ into the two files that are actually used.
 *
 *   claude-theme.js    the whole thing as one script, for a console paste
 *   extension/theme.js the same code as a content script, wrapped so it waits
 *                      for the app to finish loading before it installs
 *
 * The modules under src/ are fragments of one IIFE and share its scope, so the
 * order below is load-bearing: palettes before the remap, state before the UI,
 * boot last. Concatenating them is what keeps the shipped script readable —
 * the point of both files is that you can read them before you run them.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = dirname(fileURLToPath(import.meta.url));
const read = p => readFileSync(join(root, p), "utf8").trimEnd();

const SOURCES = [
  "src/constants.js",
  "src/palettes/dark.js",
  "src/palettes/light.js",
  "src/palettes/index.js",
  "src/color.js",
  "src/baseline.js",
  "src/remap/rules.js",
  "src/remap/curve.js",
  "src/remap/value.js",
  "src/session-palette.js",
  "src/text-settings.js",
  "src/fonts/detect.js",
  "src/fonts/catalog.js",
  "src/fonts/stacks.js",
  "src/fonts/tokens.js",
  "src/css/helpers.js",
  "src/css/build.js",
  "src/css/base.js",
  "src/css/inject.js",
  "src/state/storage.js",
  "src/state/settings.js",
  "src/state/sessions.js",
  "src/panes.js",
  "src/session-icons.js",
  "src/status.js",
  "src/expand.js",
  "src/rows.js",
  "src/apply-theme.js",
  "src/panel/overlay.js",
  "src/panel/customize.js",
  "src/panel/render.js",
  "src/panel/wire.js",
  "src/panel/dismiss.js",
  "src/lifecycle/observers.js",
  "src/lifecycle/windows.js",
  "src/lifecycle/teardown.js",
  "src/boot.js",
];

const BANNER = `/* claude-theme.js — generated by build.mjs from src/. Do not edit directly;
 * edit the modules under src/ and rebuild.
 *
 * Chrome themes and per-session accent colours for Claude Desktop (macOS).
 * Paste into the DevTools console of the *claude.ai* view (the window whose
 * <html> has data-build-id, NOT the file:// title-bar window), or install it
 * permanently through the extension in extension/ — see README.md.
 *
 * Palettes adapted from cctheme (MIT, https://github.com/Burzu8/cctheme).
 *
 * Toggle panel:  ⌥⇧T  or the colour wheel after the sidebar's back/forward.
 * Session appearance: the personalize icon in each pane's title bar.
 * Remove:        __cdtUninstall()
 * ========================================================================== */`;

const OPEN = `(() => {\n  'use strict';\n`;
const CLOSE = `})();`;

const script = `${BANNER}\n\n${OPEN}\n${SOURCES.map(read).join("\n\n")}\n${CLOSE}\n`;
writeFileSync(join(root, "claude-theme.js"), script);

/* The extension body is claude-theme.js verbatim, so a console paste and a
 * startup load run exactly the same code in the same page and the same world. */
const WRAPPER_HEAD = `/* Claude Themes content script — generated by build.mjs. Do not edit: the body
 * below is claude-theme.js verbatim; this wrapper only decides WHEN it runs.
 * Loaded by Chromium as a MAIN-world content script, so it behaves exactly like
 * a console paste (same window, same history, same storage). */
(() => {
  'use strict';
  if (window.top !== window || window.__cdtBooted) return;
  window.__cdtBooted = true;

  // The theme captures the app's live --cds-* values once, at install, so it
  // must not run until the app's stylesheets are in. Ready means: the token
  // resolves, <body> exists, and the stylesheet count has stopped changing.
  const STABLE_MS = 800, POLL_MS = 250, GIVE_UP_MS = 120000;
  const t0 = Date.now();
  let lastCount = -1, stableSince = 0;

  const tokenReady = () => !!document.body && getComputedStyle(document.documentElement)
    .getPropertyValue('--cds-text-primary').trim() !== '';

  function tick() {
    if (Date.now() - t0 > GIVE_UP_MS) {
      console.warn('claude-themes: app styles never appeared; not installing on this page.');
      return;
    }
    const n = document.styleSheets.length;
    if (n !== lastCount) { lastCount = n; stableSince = Date.now(); }
    if (!tokenReady() || Date.now() - stableSince < STABLE_MS) { setTimeout(tick, POLL_MS); return; }
    // A parent window's best-effort window.open hook may already have pushed
    // its stylesheet in here; capturing the baseline over it would snapshot
    // our own output instead of the app's.
    document.getElementById('cdt-style')?.remove();
    try { run(); } catch (e) { console.error('claude-themes failed to start:', e); }
  }

  if (document.readyState === 'complete') tick();
  else window.addEventListener('load', tick, { once: true });

  function run() {
// ───────────────────────── claude-theme.js (verbatim) ─────────────────────────
`;

const WRAPPER_TAIL = `
// ─────────────────────────────── end verbatim ────────────────────────────────
  }
})();
`;

writeFileSync(join(root, "extension", "theme.js"), WRAPPER_HEAD + script + WRAPPER_TAIL);

const lines = n => readFileSync(n, "utf8").split("\n").length - 1;
console.log(`claude-theme.js    ${lines(join(root, "claude-theme.js"))} lines`);
console.log(`extension/theme.js ${lines(join(root, "extension", "theme.js"))} lines`);
